"""Export the doodle classifier as a second ExecuTorch program for the Ethos-U85.

Same flow as create_ai_layer.py (int8 PT2E quantization, Ethos-U partitioner,
Vela), using the Vela settings of cmsis-executorch.cbuild-mlops.yml, but written
to board/DevKit-E8/doodle_pte.c/.h so it sits next to the main AI layer model.

Run from the repo root:  .venv/Scripts/python.exe model/doodle/export_doodle.py
"""

import sys
from pathlib import Path

import numpy as np
import torch
import yaml

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))

import create_ai_layer  # noqa: E402
from doodle_net import CLASSES, INPUT_SHAPE, DoodleNet  # noqa: E402


def main():
    from executorch.backends.arm.ethosu import EthosUPartitioner
    from executorch.backends.arm.quantizer import EthosUQuantizer, get_symmetric_quantization_config
    from executorch.exir import EdgeCompileConfig, ExecutorchBackendConfig, to_edge_transform_and_lower
    from torchao.quantization.pt2e.quantize_pt2e import convert_pt2e, prepare_pt2e

    mlops_file = ROOT / "cmsis-executorch.cbuild-mlops.yml"
    mlops = yaml.safe_load(mlops_file.read_text())["cbuild-mlops"]
    spec = create_ai_layer.compile_spec(mlops, mlops_file.parent)

    model = DoodleNet()
    model.load_state_dict(torch.load(HERE / "doodle_net.pt", map_location="cpu"))
    model.eval()

    # calibration: real drawings from every class
    xs = []
    for c in CLASSES:
        a = np.load(HERE / "data" / f"{c.replace(' ', '_')}.npy")[:40]
        xs.append(torch.from_numpy(a).float().unsqueeze(1) / 255.0)
    calib = torch.cat(xs)
    example = (calib[:1],)

    graph = torch.export.export(model, example).module()
    q = EthosUQuantizer(spec)
    q.set_global(get_symmetric_quantization_config(is_per_channel=True))
    prepared = prepare_pt2e(graph, q)
    with torch.no_grad():
        for i in range(len(calib)):
            prepared(calib[i:i + 1])
    quantized = convert_pt2e(prepared)
    with torch.no_grad():
        f = model(calib)
        qq = torch.cat([quantized(calib[i:i + 1]) for i in range(len(calib))])
    agree = (f.argmax(1) == qq.argmax(1)).float().mean().item()
    print(f"[doodle] float vs int8 agree on {agree * 100:.1f}% of {len(calib)} calibration drawings")

    edge = to_edge_transform_and_lower(
        torch.export.export(quantized, example),
        partitioner=[EthosUPartitioner(spec)],
        compile_config=EdgeCompileConfig(_check_ir_validity=False),
    )
    pte = bytes(edge.to_executorch(ExecutorchBackendConfig(extract_delegate_segments=False)).buffer)

    out = ROOT / "board" / "DevKit-E8"
    body = ",\n".join("  " + ", ".join(f"0x{b:02x}" for b in pte[i:i + 16]) for i in range(0, len(pte), 16))
    (out / "doodle_pte.c").write_text(
        "// Generated by model/doodle/export_doodle.py -- do not edit.\n"
        "// Doodle classifier (Quick, Draw! classes: " + ", ".join(CLASSES) + ")\n"
        "__attribute__((aligned(16))) const unsigned char doodle_pte[] = {\n" + body + "\n};\n"
        "const unsigned long doodle_pte_size = sizeof(doodle_pte);\n")
    (out / "doodle_pte.h").write_text(
        "// Generated by model/doodle/export_doodle.py -- do not edit.\n#pragma once\n"
        "#ifdef __cplusplus\nextern \"C\" {\n#endif\n"
        "extern const unsigned char doodle_pte[];\nextern const unsigned long doodle_pte_size;\n"
        f"#define DOODLE_N_CLASSES {len(CLASSES)}\n"
        "#ifdef __cplusplus\n}\n#endif\n")
    print(f"[doodle] wrote {out / 'doodle_pte.c'} ({len(pte)} bytes)")


if __name__ == "__main__":
    main()
