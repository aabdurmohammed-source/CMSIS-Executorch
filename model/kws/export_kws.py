"""Export the keyword spotter as an ExecuTorch program for the Ethos-U85
(same flow as model/doodle/export_doodle.py) -> board/DevKit-E8/kws_pte.c/.h.

Run from the repo root:  .venv/Scripts/python.exe model/kws/export_kws.py
(--untrained exports random weights, to test the pipeline before training)
"""

import sys
from pathlib import Path

import numpy as np
import torch
import yaml

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))

import create_ai_layer  # noqa: E402
from kws_features import CLASSES  # noqa: E402
from kws_net import INPUT_SHAPE, KwsNet  # noqa: E402


def main():
    from executorch.backends.arm.ethosu import EthosUPartitioner
    from executorch.backends.arm.quantizer import EthosUQuantizer, get_symmetric_quantization_config
    from executorch.exir import EdgeCompileConfig, ExecutorchBackendConfig, to_edge_transform_and_lower
    from torchao.quantization.pt2e.quantize_pt2e import convert_pt2e, prepare_pt2e

    mlops_file = ROOT / "cmsis-executorch.cbuild-mlops.yml"
    mlops = yaml.safe_load(mlops_file.read_text())["cbuild-mlops"]
    spec = create_ai_layer.compile_spec(mlops, mlops_file.parent)

    model = KwsNet()
    untrained = "--untrained" in sys.argv
    if not untrained:
        model.load_state_dict(torch.load(HERE / "kws_net.pt", map_location="cpu"))
    model.eval()
    if untrained or not (HERE / "calib.npy").exists():
        calib = torch.randn(64, *INPUT_SHAPE[1:]) * 0.6
    else:
        calib = torch.from_numpy(np.load(HERE / "calib.npy")).float()
    example = (calib[:1],)

    graph = torch.export.export(model, example).module(check_guards=False)
    q = EthosUQuantizer(spec)
    q.set_global(get_symmetric_quantization_config(is_per_channel=True))
    prepared = prepare_pt2e(graph, q)
    with torch.no_grad():
        for i in range(len(calib)):
            prepared(calib[i:i + 1])
    quantized = convert_pt2e(prepared)
    with torch.no_grad():
        f = model(calib)
        qq = torch.cat([quantized(calib[i:i + 1]) for i in range(len(calib))])
    agree = (f.argmax(1) == qq.argmax(1)).float().mean().item()
    print(f"[kws] float vs int8 agree on {agree * 100:.1f}% of {len(calib)} calibration clips")

    edge = to_edge_transform_and_lower(
        torch.export.export(quantized, example),
        partitioner=[EthosUPartitioner(spec)],
        compile_config=EdgeCompileConfig(_check_ir_validity=False),
    )
    pte = bytes(edge.to_executorch(ExecutorchBackendConfig(extract_delegate_segments=False)).buffer)

    out = ROOT / "board" / "DevKit-E8"
    body = ",\n".join("  " + ", ".join(f"0x{b:02x}" for b in pte[i:i + 16]) for i in range(0, len(pte), 16))
    (out / "kws_pte.c").write_text(
        "// Generated by model/kws/export_kws.py -- do not edit.\n"
        "// Keyword spotter (Speech Commands classes: " + ", ".join(CLASSES) + ")"
        + (" -- UNTRAINED placeholder" if untrained else "") + "\n"
        "__attribute__((aligned(16))) const unsigned char kws_pte[] = {\n" + body + "\n};\n"
        "const unsigned long kws_pte_size = sizeof(kws_pte);\n")
    print(f"[kws] wrote {out / 'kws_pte.c'} ({len(pte)} bytes)")


if __name__ == "__main__":
    main()
