"""Export Google's BlazeFace face detector (PyTorch port: github.com/hollance/BlazeFace-PyTorch,
MIT licence, files in model/blazeface/download/) as a third ExecuTorch program for the Ethos-U85.

Input: 1x3x128x128 float, RGB scaled to [-1, 1] (the CPU does that from the camera crop).
Output: 1x896x17 = for each of the 896 anchors, 16 box/keypoint regressors + 1 score logit
(the same raw tensors as BlazeFace.forward, concatenated; decoding + NMS run on the CPU).

Same flow as create_ai_layer.py (Vela settings of cmsis-executorch.cbuild-mlops.yml),
16-bit activations. Writes board/DevKit-E8/face_pte.c/.h and model/blazeface/anchors.h.

Run from the repo root:  .venv/Scripts/python.exe model/blazeface/export_blazeface.py
"""

import os
import sys
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F
import yaml

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
DL = HERE / "download"
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(DL))

import create_ai_layer  # noqa: E402
from blazeface import BlazeFace  # noqa: E402


class BlazeFaceRaw(torch.nn.Module):
    def __init__(self, bf):
        super().__init__()
        self.bf = bf

    def forward(self, x):
        r, c = self.bf(x)
        return torch.cat((r, c), dim=2)  # 1 x 896 x 17


def calibration_images(n=48):
    """Olivetti faces (grey, 64x64) pasted at random sizes/places onto random
    backgrounds, as RGB 128x128 in [-1, 1]."""
    from sklearn.datasets import fetch_olivetti_faces

    faces = fetch_olivetti_faces(data_home=os.environ.get("TEMP", "."), download_if_missing=True).images
    g = torch.Generator().manual_seed(0)
    out = []
    for i in range(n):
        bg = torch.rand(3, 1, 1, generator=g) * 0.8 + 0.1 + torch.randn(3, 128, 128, generator=g) * 0.05
        size = int(torch.randint(40, 100, (1,), generator=g))
        f = torch.from_numpy(faces[i * 7 % len(faces)]).unsqueeze(0).unsqueeze(0)
        f = F.interpolate(f, size=(size, size), mode="bilinear", align_corners=False)[0]
        x0 = int(torch.randint(0, 128 - size + 1, (1,), generator=g))
        y0 = int(torch.randint(0, 128 - size + 1, (1,), generator=g))
        bg[:, y0:y0 + size, x0:x0 + size] = f.expand(3, -1, -1) * torch.tensor([1.0, 0.85, 0.75]).view(3, 1, 1)
        out.append((bg.clamp(0, 1) * 2 - 1).unsqueeze(0))
    return out


def main():
    from executorch.backends.arm.ethosu import EthosUPartitioner
    from executorch.backends.arm.quantizer import EthosUQuantizer
    from executorch.backends.arm.quantizer.arm_quantizer import get_symmetric_a16w8_quantization_config
    from executorch.exir import EdgeCompileConfig, ExecutorchBackendConfig, to_edge_transform_and_lower
    from torchao.quantization.pt2e.quantize_pt2e import convert_pt2e, prepare_pt2e

    mlops_file = ROOT / "cmsis-executorch.cbuild-mlops.yml"
    mlops = yaml.safe_load(mlops_file.read_text())["cbuild-mlops"]
    spec = create_ai_layer.compile_spec(mlops, mlops_file.parent)

    bf = BlazeFace(back_model=False)
    bf.load_state_dict(torch.load(DL / "blazeface.pth", map_location="cpu", weights_only=True))
    bf.eval()
    model = BlazeFaceRaw(bf).eval()

    calib = calibration_images()
    example = (calib[0],)
    graph = torch.export.export(model, example).module()
    q = EthosUQuantizer(spec)
    q.set_global(get_symmetric_a16w8_quantization_config(is_per_channel=True))
    prepared = prepare_pt2e(graph, q)
    with torch.no_grad():
        for x in calib:
            prepared(x)
    quantized = convert_pt2e(prepared)
    with torch.no_grad():
        f = torch.cat([model(x) for x in calib[:8]])
        qq = torch.cat([quantized(x) for x in calib[:8]])
    sf, sq = f[..., 16].sigmoid(), qq[..., 16].sigmoid()
    print(f"[face] score mean abs diff float vs a16w8: {(sf - sq).abs().mean():.4f}; "
          f"max score float {sf.max():.3f} / quantized {sq.max():.3f}")

    edge = to_edge_transform_and_lower(
        torch.export.export(quantized, example),
        partitioner=[EthosUPartitioner(spec)],
        compile_config=EdgeCompileConfig(_check_ir_validity=False),
    )
    pte = bytes(edge.to_executorch(ExecutorchBackendConfig(extract_delegate_segments=False)).buffer)

    out = ROOT / "board" / "DevKit-E8"
    body = ",\n".join("  " + ", ".join(f"0x{b:02x}" for b in pte[i:i + 16]) for i in range(0, len(pte), 16))
    (out / "face_pte.c").write_text(
        "// Generated by model/blazeface/export_blazeface.py -- do not edit.\n"
        "// BlazeFace front model (MediaPipe; PyTorch port by M. Hollemans, MIT licence)\n"
        "__attribute__((aligned(16))) const unsigned char face_pte[] = {\n" + body + "\n};\n"
        "const unsigned long face_pte_size = sizeof(face_pte);\n")
    anchors = np.load(DL / "anchors.npy").astype(np.float32)  # 896 x 4: x_center, y_center, w, h (0..1)
    rows = ",\n".join("    {%.6ff, %.6ff, %.6ff, %.6ff}" % tuple(a) for a in anchors)
    (out / "face_anchors.h").write_text(
        "// Generated by model/blazeface/export_blazeface.py -- do not edit.\n#pragma once\n"
        "// BlazeFace front-model anchors: x_center, y_center, w, h (fractions of the 128x128 input)\n"
        f"#define FACE_N_ANCHORS {len(anchors)}\n"
        "static const float face_anchors[FACE_N_ANCHORS][4] = {\n" + rows + "\n};\n")
    print(f"[face] wrote {out / 'face_pte.c'} ({len(pte)} bytes) and face_anchors.h")


if __name__ == "__main__":
    main()
